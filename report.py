#!/usr/bin/env python3
"""Turn a raw sweep into manuscript-candidate, clearly-labelled diagnostic output.

Given a results directory it:
  1. regenerates representative per-tick timeseries (rep 0 of each cell, seeded,
     so it reproduces exactly what the sweep ran) -> timeseries/*.csv
  2. renders figures (adoption curves incl. the plateau-then-jump wedge,
     capacity terrain, per-phase focal sweeps) -> figures/*.png
  3. writes REPORT.md with a DIAGNOSTIC banner, run provenance, invariant status,
     and per-phase verdicts
  4. refreshes results/README.md (the convention + the diagnostic tag)

  python report.py                 # newest results/ dir
  python report.py results/<dir>
"""

import csv
import glob
import json
import os
import sys

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from abm import phases as P
from abm.model import World

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from analyze import verdict, f as fnum, num, load  # reuse verdict logic


DIAGNOSTIC_BANNER = (
    "> **STATUS: DIAGNOSTIC — provisional model output.**\n"
    "> Generated by the progressive-build test sweep of the latent-adoption ABM. "
    "These are *model* results (not yet validated against any empirical record). "
    "Figures and tables here are candidates for the manuscript's methods/results "
    "sections, pending review. Every run is seeded and reproducible from "
    "`metadata.json`. Regenerate with `python report.py <dir>`.\n"
)


def latest_results_dir() -> str:
    here = os.path.dirname(os.path.abspath(__file__))
    dirs = [d for d in sorted(glob.glob(os.path.join(here, "results", "*")))
            if os.path.isfile(os.path.join(d, "aggregated.csv"))]
    if not dirs:
        sys.exit("no results found; run a sweep first")
    return dirs[-1]


# ---------------------------------------------------------------------------
# 1. representative timeseries
# ---------------------------------------------------------------------------
def regen_timeseries(rdir, meta):
    base_seed = meta.get("base_seed", 0)
    tdir = os.path.join(rdir, "timeseries")
    os.makedirs(tdir, exist_ok=True)
    series = {}  # (phase, focal_value) -> list of per-tick dicts
    for pid in meta["phases"]:
        phase = P.PHASE_INDEX[pid]
        fp = phase["focal"]["param"]
        for val in phase["focal"]["values"]:
            cfg = P.config_for_phase(pid, {fp: val, "seed": base_seed})
            w = World(cfg)
            w.run()
            rows = []
            for h in w.history:
                row = {
                    "t": h["t"],
                    "manifest_share": round(h["manifest_share"], 5),
                    "element_saturation": round(h["element_saturation"], 5),
                    "bigthing_element_saturation": round(h["bigthing_element_saturation"], 5),
                    "observability_gap": round(h["observability_gap"], 5),
                }
                for lab, pb in h["per_big"].items():
                    row[f"{lab}_manifest"] = pb["manifest"]
                    row[f"{lab}_latent"] = pb["latent"]
                rows.append(row)
            fname = f"{pid}__{fp}={val}.csv"
            with open(os.path.join(tdir, fname), "w", newline="") as fh:
                wr = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
                wr.writeheader(); wr.writerows(rows)
            series[(pid, str(val))] = rows
    return series


# ---------------------------------------------------------------------------
# 2. figures
# ---------------------------------------------------------------------------
def fig_wedge_curves(series, fdir):
    """The headline: adoption over time under the three transmissibility modes."""
    modes = ["elements_only", "whole_package", "both"]
    colors = {"elements_only": "#2563eb", "whole_package": "#dc2626", "both": "#16a34a"}
    plt.figure(figsize=(7, 4.2))
    for m in modes:
        rows = series.get(("V1-W", m))
        if not rows:
            continue
        plt.plot([r["t"] for r in rows], [r["manifest_share"] for r in rows],
                 label=m, color=colors[m], lw=2)
    plt.xlabel("tick"); plt.ylabel("manifest share")
    plt.title("V1-W — the transmissibility wedge\n(elements-only = latent adoption; "
              "whole-package = standard contagion)")
    plt.legend(); plt.ylim(-0.02, 1.02); plt.grid(alpha=0.25); plt.tight_layout()
    _save(fdir, "01_wedge_adoption_curves.png")


def fig_capacity_terrain(agg, fdir):
    rows = [r for r in agg if r["phase"] == "V1"]
    if not rows:
        return
    rows.sort(key=lambda r: num(r["focal_value"]))
    x = [num(r["focal_value"]) for r in rows]
    y = [fnum(r, "final_manifest_share_mean") for r in rows]
    e = [fnum(r, "final_manifest_share_sd") for r in rows]
    plt.figure(figsize=(7, 4.2))
    plt.errorbar(x, y, yerr=e, marker="o", color="#7c3aed", lw=2, capsize=4)
    plt.xlabel("capacity cap"); plt.ylabel("final manifest share")
    plt.title("V1 — capacity drives the adoption regime\n"
              "(competition engine: threshold-to-capacity ratio)")
    plt.ylim(-0.02, 1.02); plt.grid(alpha=0.25); plt.tight_layout()
    _save(fdir, "02_v1_capacity_terrain.png")


def fig_plateau_jump(series, fdir):
    """Element saturation rising smoothly vs big-thing adoption jumping: the
    observability asymmetry + plateau-then-jump in one panel (V1, capacity=6)."""
    rows = series.get(("V1", "6")) or next((v for (k, _), v in
                      [((kk, None), vv) for kk, vv in series.items() if kk[0] == "V1"]), None)
    if not rows:
        return
    plt.figure(figsize=(7, 4.2))
    t = [r["t"] for r in rows]
    plt.plot(t, [r["element_saturation"] for r in rows], label="element saturation (visible-to-us)",
             color="#a3e635", lw=2)
    plt.plot(t, [r["manifest_share"] for r in rows], label="manifest share (the big thing)",
             color="#2563eb", lw=2)
    plt.xlabel("tick"); plt.ylabel("fraction")
    plt.title("V1 — preparation rises smoothly, manifestation jumps\n"
              "(latent reservoir + trigger-driven flips)")
    plt.legend(); plt.ylim(-0.02, 1.02); plt.grid(alpha=0.25); plt.tight_layout()
    _save(fdir, "03_v1_plateau_then_jump.png")


def fig_change_agent(series, fdir):
    rows_by_val = {k[1]: v for k, v in series.items() if k[0] == "change-agent"}
    if not rows_by_val:
        return
    plt.figure(figsize=(7, 4.2))
    for val, rows in sorted(rows_by_val.items(), key=lambda kv: num(kv[0])):
        plt.plot([r["t"] for r in rows], [r["manifest_share"] for r in rows],
                 lw=2, label=f"change-agent frac={val}")
    plt.xlabel("tick"); plt.ylabel("manifest share")
    plt.title("Change-agent scenario — equipped minority, unprepared population\n"
              "(failed diffusion under elements-only transmission)")
    plt.legend(); plt.ylim(-0.02, 1.02); plt.grid(alpha=0.25); plt.tight_layout()
    _save(fdir, "04_change_agent_failed_diffusion.png")


def fig_all_phase_sweeps(agg, fdir):
    phases, order = {}, []
    for r in agg:
        phases.setdefault(r["phase"], []).append(r)
        if r["phase"] not in order:
            order.append(r["phase"])
    n = len(order)
    cols = 3
    rows_n = (n + cols - 1) // cols
    fig, axes = plt.subplots(rows_n, cols, figsize=(4 * cols, 3 * rows_n))
    axes = axes.flatten()
    for i, pid in enumerate(order):
        ax = axes[i]
        rr = sorted(phases[pid], key=lambda r: (isinstance(num(r["focal_value"]), str),
                                                num(r["focal_value"])))
        labels = [str(r["focal_value"]) for r in rr]
        y = [fnum(r, "final_manifest_share_mean") for r in rr]
        ax.plot(range(len(y)), y, marker="o", color="#0ea5e9")
        ax.set_xticks(range(len(labels)))
        ax.set_xticklabels(labels, rotation=30, ha="right", fontsize=7)
        ax.set_title(f"{pid}\n({rr[0]['focal_param']})", fontsize=8)
        ax.set_ylim(-0.02, 1.02); ax.grid(alpha=0.2)
    for j in range(n, len(axes)):
        axes[j].axis("off")
    fig.suptitle("Final manifest share across every phase's focal sweep", fontsize=11)
    fig.tight_layout(rect=[0, 0, 1, 0.97])
    _save(fdir, "05_all_phase_sweeps.png", fig=fig)


def _save(fdir, name, fig=None):
    path = os.path.join(fdir, name)
    (fig or plt).savefig(path, dpi=130)
    plt.close(fig if fig else None)
    return name


# ---------------------------------------------------------------------------
# 3. REPORT.md
# ---------------------------------------------------------------------------
def write_report(rdir, meta, agg, figs):
    phases, order = {}, []
    for row in agg:
        phases.setdefault(row["phase"], []).append(row)
        if row["phase"] not in order:
            order.append(row["phase"])

    lines = [f"# Sweep report — {os.path.basename(rdir)}", "", DIAGNOSTIC_BANNER, ""]
    lines += [
        "## Provenance", "",
        f"- created: {meta.get('created')}",
        f"- phases: {', '.join(meta.get('phases', []))}",
        f"- replications per cell: {meta.get('replications')}",
        f"- base seed: {meta.get('base_seed')}",
        f"- invariants asserted every run: {meta.get('with_invariants')}",
        f"- model registry snapshot: see `metadata.json`",
        "",
        "## Files", "",
        "- `summary.csv` — one row per replication (all signatures)",
        "- `aggregated.csv` — mean/sd per (phase, focal value) cell",
        "- `timeseries/*.csv` — representative per-tick trace (rep 0) of each cell",
        "- `figures/*.png` — see below",
        "- `metadata.json` — full parameter registry + phase definitions",
        "",
        "## Figures", "",
    ]
    for fpng in figs:
        lines.append(f"- `figures/{fpng}`")
    lines += ["", "## Per-phase verdicts", "",
              "| phase | focal | range (manifest share) | verdict |",
              "|---|---|---|---|"]
    for pid in order:
        rr = sorted(phases[pid], key=lambda r: (isinstance(num(r["focal_value"]), str),
                                                num(r["focal_value"])))
        shares = [fnum(r, "final_manifest_share_mean") for r in rr]
        rng = f"{min(shares):.2f}–{max(shares):.2f}" if shares else "—"
        lines.append(f"| {pid} | {rr[0]['focal_param']} | {rng} | {verdict(pid, rr, shares)} |")
    lines += ["", "## Per-phase focal sweeps", ""]
    for pid in order:
        rr = sorted(phases[pid], key=lambda r: (isinstance(num(r["focal_value"]), str),
                                                num(r["focal_value"])))
        fp = rr[0]["focal_param"]
        lines += [f"### {pid} (sweep: {fp})", "",
                  "| value | manifest share | element sat | max jump | t→½ | obs gap |",
                  "|---|---|---|---|---|---|"]
        for r in rr:
            lines.append(
                f"| {r['focal_value']} | {fnum(r,'final_manifest_share_mean'):.3f} "
                f"±{fnum(r,'final_manifest_share_sd'):.3f} "
                f"| {fnum(r,'final_element_saturation_mean'):.3f} "
                f"| {fnum(r,'max_single_tick_jump_mean'):.3f} "
                f"| {fnum(r,'time_to_half_cascade_mean'):.0f} "
                f"| {fnum(r,'final_observability_gap_mean'):.3f} |")
        lines.append("")
    with open(os.path.join(rdir, "REPORT.md"), "w") as fh:
        fh.write("\n".join(lines))


def write_results_readme():
    here = os.path.dirname(os.path.abspath(__file__))
    path = os.path.join(here, "results", "README.md")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fh:
        fh.write(
            "# Results — DIAGNOSTIC model output\n\n"
            "Each `YYYYMMDD-HHMMSS-<tag>/` directory is one sweep of the "
            "latent-adoption ABM.\n\n"
            + DIAGNOSTIC_BANNER +
            "\nThese are reproducible *model* outputs from the progressive-build "
            "test sweeps. They are valuable diagnostic data and several figures "
            "are manuscript candidates, but nothing here has been validated "
            "against an empirical record yet — treat as provisional.\n\n"
            "Per directory:\n"
            "- `REPORT.md` — human-readable report (start here)\n"
            "- `summary.csv`, `aggregated.csv` — the data\n"
            "- `timeseries/` — per-tick traces\n"
            "- `figures/` — rendered figures\n"
            "- `metadata.json` — full provenance (params, phases, seeds)\n")


def main():
    rdir = sys.argv[1] if len(sys.argv) > 1 else latest_results_dir()
    print(f"reporting on {os.path.basename(rdir)} …")
    with open(os.path.join(rdir, "metadata.json")) as fh:
        meta = json.load(fh)
    agg = load(os.path.join(rdir, "aggregated.csv"))

    print("  regenerating representative timeseries …")
    series = regen_timeseries(rdir, meta)

    print("  rendering figures …")
    fdir = os.path.join(rdir, "figures")
    os.makedirs(fdir, exist_ok=True)
    fig_wedge_curves(series, fdir)
    fig_capacity_terrain(agg, fdir)
    fig_plateau_jump(series, fdir)
    fig_change_agent(series, fdir)
    fig_all_phase_sweeps(agg, fdir)
    figs = sorted(os.listdir(fdir))

    print("  writing REPORT.md + results/README.md …")
    write_report(rdir, meta, agg, figs)
    write_results_readme()
    print(f"done -> {os.path.join(rdir, 'REPORT.md')}")


if __name__ == "__main__":
    main()
